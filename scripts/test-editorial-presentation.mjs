#!/usr/bin/env node
import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const raw=JSON.parse(read('cakes.json'));
const pub=JSON.parse(read('assets/public-creations.json'));
const brand=read('assets/brand-site.css'),site=read('assets/brand-site.js');
const pages=['index.html','weddings/index.html','celebrations/index.html','tiramisu-cakes/index.html','decorate-and-sip/index.html','cake-care/index.html','cakes/index.html','enquire/index.html','about/index.html','404.html'];
const privateSelected=raw.cakes.filter(c=>c.featured30);
const items=pub.creations;
assert.equal(privateSelected.length,120);
assert.equal(items.length,120,'Final owner selections must remain 120');
assert.equal(pub.count,120,'Public count must match featured total');
assert.equal(new Set(items.map(c=>c.code)).size,120,'No duplicate image source');
assert.deepEqual(new Set(items.map(c=>c.code)),new Set(privateSelected.map(c=>c.sourceShortcode)),'All owner selections retained');
assert.equal(items.filter(c=>c.section==='weddings').length,9);
assert.equal(items.filter(c=>c.section==='tiramisu').length,1);
assert.equal(items.filter(c=>c.section==='celebrations').length,110);
assert(items.every(c=>c.title&&c.title.length<75&&!/[\u{1F300}-\u{1FAFF}]/u.test(c.title)&&!c.title.includes('@studi')),'Every public title should be editorial, not an Instagram caption');
assert(items.every(c=>c.alt&&c.alt.length<150),'Alt text must be descriptive and bounded');
assert(items.every(c=>/^https:\/\/www\.instagram\.com\/p\/[A-Za-z0-9_-]{5,32}\/$/.test(c.instagramUrl)));
assert(items.every(c=>fs.existsSync(c.coverImage)&&fs.existsSync(c.thumbnailImage||c.coverImage)),'Every original selected image must be present');
const keys=new Set(['id','code','title','alt','coverImage','thumbnailImage','instagramUrl','section','occasion','productTypes','priority']);
for(const item of items)assert(Object.keys(item).every(k=>keys.has(k)),'Public gallery contains internal field');
assert(!/captionEvidence|ownerReviewDecision|reviewNotes|publicationHoldReasons|approvalStatus|postEngagement|customer|supplier/i.test(read('assets/public-creations.json')),'Raw private metadata must not be in public gallery');
assert(brand.includes('#9A2849')&&brand.includes('#F6F4F0'),'Use exact brand palette');
for(const font of ['Perandory Condensed','Amorea','Amsterdam Four','Helvetica Now Display'])assert(brand.includes(font),'Named brand font missing: '+font);
assert(!brand.includes('#fedcde')&&!brand.includes('#f15ea0'),'Legacy colours cannot return');
assert(read('assets/brand/wordmark-set-2.svg').includes('data:image/webp;base64,'),'Do not claim a raster logo has become true vector');
assert(site.includes("const PHONE='0425 819 951'"),'Confirmed owner phone missing');
assert(site.includes('const IG_DM='),'Direct Instagram messaging missing');
assert(site.includes("const DATA='/assets/public-creations.json'"),'Public minimal gallery source missing');
assert(!site.includes("fetch('/cakes.json'"),'Internal raw catalogue must never be fetched by visitors');
assert(site.includes('filter-chip')&&site.includes('Show more creations'),'Gallery filtering and progressive loading missing');
assert(site.includes('creation-dialog')&&site.includes('Copy reference'),'Preview and design reference missing');
assert(!/add to cart|checkout|select a date|book now/i.test(site),'No online order or booking flow');
const ignore=read('.assetsignore'),wrangler=JSON.parse(read('wrangler.jsonc'));
for(const p of ['cakes.json','data/','review/','assets/gallery-review.js'])assert(ignore.includes(p),'Sensitive data not excluded from Worker assets: '+p);
assert.equal(wrangler.assets.not_found_handling,'404-page');
for(const p of pages){
 const h=read(p);
 assert(h.includes('noindex,nofollow'),'Preview must remain non-indexed: '+p);
 assert(h.includes('brand-site.css?v=20261102-r1')&&h.includes('brand-site.js?v=20261102-r1'),'New assets missing: '+p);
 assert(h.includes('/assets/brand/wordmark-set-2.svg'),'Brand wordmark missing: '+p);
 for(const path of ['weddings','celebrations','tiramisu-cakes','decorate-and-sip','cake-care'])assert(h.includes('href="/'+path+'/"'),'Nav missing '+path+' on '+p);
 assert(h.includes('href="tel:+61425819951"'),'Phone link missing: '+p);
 assert(h.includes('https://www.instagram.com/madsaboutcake/'),'Instagram profile fallback missing: '+p);
 assert(h.includes('<main id="main">')&&h.includes('<h1'),'Semantic heading missing: '+p);
}
for(const p of ['weddings/index.html','celebrations/index.html','tiramisu-cakes/index.html','cakes/index.html']){
 const h=read(p);
 assert(h.includes('data-gallery='),'Gallery missing: '+p);
 assert(h.includes('id="gallery-count" aria-live="polite"'),'Accessible count missing: '+p);
 assert(!h.includes('class="gallery" aria-live="polite"'),'Do not announce 120 cards to screen readers: '+p);
 assert(h.includes('id="gallery-show-more"'),'Incremental gallery missing: '+p);
 assert(h.includes('gallery-section-heading'),'Semantic gallery heading missing: '+p);
}
for(const p of ['celebrations/index.html','cakes/index.html'])assert(read(p).includes('id="gallery-filters"'),'Filter chips missing: '+p);
const home=read('index.html');
assert.equal((home.match(/class="category-card"/g)||[]).length,4,'Four main owner-requested categories');
assert(home.includes('href="/cakes/">Explore our creations ↗'),'Explore all should link to All creations');
const wedding=read('weddings/index.html');assert(wedding.includes('engagement celebrations'),'Wedding copy must acknowledge bridal/engagements');
const workshop=read('decorate-and-sip/index.html');
assert.equal((workshop.match(/DSR06gjEgJK-no-visible-faces\.webp/g)||[]).length,1,'Do not reuse workshop photo');
assert(workshop.includes('DHDXe4EB9Le-cupcake-edition.webp'),'Original workshop photo missing');
const care=read('cake-care/index.html');
for(const x of ['passenger-side floor','lap','support it from underneath','squeezing the sides'])assert(care.includes(x),'Owner-supplied care tips missing: '+x);
assert(!/fridge|refrigerat|room.temperature|store for/i.test(care),'Do not invent storage directions');
const contact=read('enquire/index.html');
assert(contact.includes('Helpful details for your message'),'Enquiry guidance missing');
assert(!contact.includes('<form'),'Manual enquiry only: do not add checkout or form');
console.log('RED TEAM OWNER REVIEW PASS: 120 selected creations, minimal public JSON, no exposed review deployment, 4 categories, branded manual contact and cake-care text.');
